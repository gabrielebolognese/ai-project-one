/**
 * Pure Java source cleaning helpers (no I/O), unit-tested in clean.test.ts.
 *
 * Pipeline per file: reject early (size / generated / binary-ish) -> normalise whitespace ->
 * strip licence header -> reject late (too short, no type declaration, absurd lines).
 */
import { createHash } from "node:crypto";

export type DropReason =
  | "too_large"
  | "too_short"
  | "generated"
  | "bad_encoding"
  | "non_ascii"
  | "long_lines"
  | "no_type_decl"
  | "dup_exact"
  | "dup_near";

export const LIMITS = {
  maxRawBytes: 100 * 1024,
  minCleanBytes: 200,
  maxNonAsciiFrac: 0.02,
  maxLineLen: 600,
  nearDupChars: 2048,
} as const;

const LICENSE_WORDS = /licen[cs]e|copyright|permission is hereby granted|all rights reserved|\(c\)\s*\d{4}/i;
const GENERATED = /@(?:javax\.annotation\.(?:processing\.)?)?Generated\b|generated by the protocol buffer|DO NOT EDIT|(?:auto|machine)[- ]?generated|code generated|this file (?:is|was) generated|\/\/ Generated\b/i;
const TYPE_DECL = /\b(?:class|interface|enum|record|@interface)\s+[A-Za-z_$]/;

/** CRLF/CR -> LF, tabs -> 4 spaces, strip trailing spaces, collapse 3+ blank lines to 2, final newline. */
export function normalizeWhitespace(src: string): string {
  let s = src.replace(/\r\n?/g, "\n").replace(/\t/g, "    ");
  s = s.replace(/[  ]+$/gm, "");
  s = s.replace(/\n{4,}/g, "\n\n\n");
  s = s.replace(/^\n+/, "").replace(/\s+$/, "");
  return s + "\n";
}

/**
 * Remove leading block-comment or line-comment headers that look like licence/copyright
 * boilerplate. Javadoc attached to the class (after `package`/`import`) is never touched.
 */
export function stripLicenseHeader(src: string): string {
  let s = src.replace(/^﻿/, "");
  for (let round = 0; round < 3; round++) {
    const t = s.replace(/^\s+/, "");
    if (t.startsWith("/*")) {
      const end = t.indexOf("*/");
      if (end < 0) break;
      const block = t.slice(0, end + 2);
      // A header sits before `package`; a class javadoc contains no licence words and is kept.
      if (!LICENSE_WORDS.test(block)) break;
      s = t.slice(end + 2);
      continue;
    }
    if (t.startsWith("//")) {
      const lines = t.split("\n");
      let n = 0;
      while (n < lines.length && lines[n].trimStart().startsWith("//")) n++;
      const block = lines.slice(0, n).join("\n");
      if (n === 0 || !LICENSE_WORDS.test(block)) break;
      s = lines.slice(n).join("\n");
      continue;
    }
    break;
  }
  return s.replace(/^\s+/, "");
}

export function sha1(s: string): string {
  return createHash("sha1").update(s).digest("hex");
}

/** Hash of the first ~2 KB of the body with `package`/`import` lines removed (near-duplicate key). */
export function nearDupKey(clean: string): string {
  const body = clean
    .split("\n")
    .filter((l) => !/^\s*(?:package|import)\s/.test(l))
    .join("\n")
    .trimStart();
  return sha1(body.slice(0, LIMITS.nearDupChars));
}

export type CleanResult = { ok: true; text: string } | { ok: false; reason: DropReason };

/** Clean one raw file. Dedup is done by the caller (it needs cross-file state). */
export function cleanJavaFile(raw: Buffer): CleanResult {
  if (raw.length > LIMITS.maxRawBytes) return { ok: false, reason: "too_large" };
  const decoded = raw.toString("utf8");
  if (decoded.includes("�")) return { ok: false, reason: "bad_encoding" };
  if (GENERATED.test(decoded)) return { ok: false, reason: "generated" };
  const text = normalizeWhitespace(stripLicenseHeader(decoded));
  if (text.length < LIMITS.minCleanBytes) return { ok: false, reason: "too_short" };
  let nonAscii = 0;
  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) > 127) nonAscii++;
  if (nonAscii / text.length > LIMITS.maxNonAsciiFrac) return { ok: false, reason: "non_ascii" };
  let maxLine = 0;
  for (const line of text.split("\n")) if (line.length > maxLine) maxLine = line.length;
  if (maxLine > LIMITS.maxLineLen) return { ok: false, reason: "long_lines" };
  if (!TYPE_DECL.test(text)) return { ok: false, reason: "no_type_decl" };
  return { ok: true, text };
}

/** License detection from the text of a LICENSE file. */
export type LicenseId = "Apache-2.0" | "MIT" | "EPL" | "unknown";
export function detectLicense(text: string): LicenseId {
  if (/Apache License/i.test(text) && /Version 2\.0/i.test(text)) return "Apache-2.0";
  if (/Eclipse Public License/i.test(text)) return "EPL";
  if (/MIT License/i.test(text) || /Permission\s+is\s+hereby\s+granted,\s+free\s+of\s+charge/i.test(text)) return "MIT";
  return "unknown";
}
